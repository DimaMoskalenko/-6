# Функція пошуку студента за ПІБ
def find_student(pib):
    """
    Пошук студента за ПІБ.
    """
    if pib in students:
        info = students[pib]
        print(f"\nЗнайдено студента: {pib}")
        print(f"Група: {info['Група']}")
        print(f"Курс: {info['Курс']}")
        print("Оцінки:")
        for subject, grade in info['Предмети та оцінки за ІІ семестр'].items():
            print(f"  {subject}: {grade}")
        print(f"Середній бал: {info['Середній бал']}")
    else:
        print("Студента не знайдено.")
