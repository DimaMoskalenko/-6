# Функція додавання нового студента
def add_student(pib, group, course, subjects):
    """
    Додає нового студента до словника.
    """
    avg = round(sum(subjects.values()) / len(subjects), 2)
    students[pib] = {
        'Група': group,
        'Курс': course,
        'Предмети та оцінки за ІІ семестр': subjects,
        'Середній бал': avg
    }
# Автор: Маслак Олександр
# Функція сортування студентів за середнім балом
def sort_by_average():
    """
    Виводить студентів, відсортованих за середнім балом.
    """
    for pib in students:
        grades = students[pib]['Предмети та оцінки за ІІ семестр']
        students[pib]['Середній бал'] = round(sum(grades.values()) / len(grades), 2)
    sorted_list = sorted(students.items(), key=lambda x: x[1]['Середній бал'], reverse=True)
    print("\nСортування за середнім балом:")
    for pib, info in sorted_list:
        print(f"{pib}: {info['Середній бал']} балів")
